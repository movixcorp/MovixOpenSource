  function getUqloadRootDomain(hostname) {
    const host = String(hostname || "")
      .toLowerCase()
      .replace(/\.$/, "");
    const labels = host.split(".");
    if (labels.length < 2) return null;
    const root = labels.slice(-2).join(".");
    return UQLOAD_ROOT_PATTERN.test(root) ? root : null;
  }

